# ⚠️ 只能**追加到末尾** —— Swift 侧 Furniture 的 case 顺序用的是这里的索引。
ORDER = ['bed', 'bowl', 'long_bowl', 'plant']

# 每件占几格宽（1 或 2）
WIDTHS = {'bed': 2, 'bowl': 1, 'long_bowl': 2, 'plant': 1}


def build():
    # 按最宽的排：每格位固定 2 格宽的空间，简化 Swift 侧取图
    slot = CELL * 2
    W, H = slot * len(ORDER), CELL
    buf = bytearray(W * H * 4)

    for i, key in enumerate(ORDER):
        rows = ICONS[key]
        want = CELL * WIDTHS[key]
        # 行数不足时在**顶部**补空行 —— 家具是贴地的，
        # 底部对齐比顶部对齐重要，补在上面不会让它悬空。
        if len(rows) < CELL:
            pad = CELL - len(rows)
            print(f"  ⚠️  {key} 少 {pad} 行，已在顶部补空")
            rows = ['.' * want] * pad + list(rows)
        assert len(rows) <= CELL, f"{key} 行数 {len(rows)} > {CELL}"
        for y, line in enumerate(rows):
            # 手绘时行尾容易少几个点，右侧用透明补齐 ——
            # 逐行数点数比让脚本补更容易出错，也更难改。
            line = line.ljust(want, '.')
            assert len(line) >= want, f"{key} y={y} 列数 {len(line)} < {want}"
            for x in range(want):
                c = PAL.get(line[x])
                if c is None:
                    raise SystemExit(f"{key} y={y} x={x} 未知图例 {line[x]!r}")
                if c[3] == 0:
                    continue
                setpx(buf, W, i * slot + x, y, c)

    save('Assets/room/furniture.png', W, H, buf)
    print(f"Assets/room/furniture.png  {W}×{H}  {len(ORDER)} 件")
    for i, k in enumerate(ORDER):
        print(f"  {i}:{k}  {WIDTHS[k]} 格宽")


if __name__ == '__main__':
    build()
