def palette_for(name, color):
    """从主 sheet 的侧视帧提取该毛色的三色 + 轮廓色。"""
    w, h, d = load(f'Assets/pets/{name}.png')
    ox = (color * 4) * CELL
    cnt = {}
    for y in range(CELL):
        for x in range(CELL):
            r, g, b, a = px(d, w, ox + x, y)
            if a > 8:
                cnt[(r, g, b)] = cnt.get((r, g, b), 0) + 1
    ranked = sorted(cnt.items(), key=lambda kv: -kv[1])
    # 按出现次数取前 4 色，再按亮度排序区分 亮/中/暗
    top = [c for c, _ in ranked[:4]]
    def lum(c): return (c[0]*299 + c[1]*587 + c[2]*114) // 1000
    top.sort(key=lum, reverse=True)
    light = top[0]
    mid = top[1] if len(top) > 1 else top[0]
    # 轮廓用最暗的
    outline = min(top, key=lum)
    # 鼻子：找暖色（R 明显大于 B），没有就用中间色
    nose = mid
    for c, _ in ranked:
        if c[0] > c[2] + 30 and lum(c) > 90:
            nose = c; break
    return {
        'L': light + (255,),
        'M': mid + (255,),
        'O': outline + (255,),
        'E': outline + (255,),
        'N': nose + (255,),
        '.': (0, 0, 0, 0),
    }

def build(name, exhale, inhale):
    OW, OH = CELL * 4, CELL * 2
    out = bytearray(OW * OH * 4)
    for color in range(4):
        pal = palette_for(name, color)
        for row, art in enumerate((exhale, inhale)):
            for y in range(CELL):
                line = art[y] if y < len(art) else '.' * CELL
                for x in range(CELL):
                    ch = line[x] if x < len(line) else '.'
                    setpx(out, OW, color * CELL + x, row * CELL + y,
                          pal.get(ch, pal['.']))
    save(f'Assets/pets/{name}_sleep.png', OW, OH, out)
    print(f"wrote Assets/pets/{name}_sleep.png {OW}x{OH} (4色 × 2帧)")

build('cat', CAT_EXHALE, CAT_INHALE)
build('dog', DOG_EXHALE, DOG_INHALE)
